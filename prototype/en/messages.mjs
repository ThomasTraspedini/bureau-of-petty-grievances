export function formatMessage(key, variables = {}) {
  const template = messages[key];
  if (typeof template !== "string") throw new Error(`Missing locale message: ${key}`);
  return template.replace(/\{([^}]+)\}/g, (_, name) => String(variables[name] ?? `{${name}}`));
}
